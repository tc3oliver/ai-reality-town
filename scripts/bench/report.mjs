#!/usr/bin/env node
/**
 * Turn the benchmark's JSON into the committed evidence table (FR-Q005 / ART-136 AC#11).
 *
 * A separate step from the run, for one reason: the JSON is the record and the markdown is a
 * rendering of it. Anyone re-reading a past result reads the JSON; the table exists so a
 * reviewer can see pass/fail without parsing numbers by eye.
 *
 * Plain Node, no transpiler and no new dependency — this is a formatter over a file the
 * benchmark already wrote, and adding a build step to a build step is not worth it.
 *
 * Exits non-zero when any measured criterion failed, so `npm run bench` is usable as a gate
 * rather than only as a report. Criteria recorded as `requires_deployment` or `unreachable` do
 * NOT fail the run — they are gaps this harness has stated, and turning a stated gap into a red
 * build would push the next person to delete the statement.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const ROOT = process.cwd();
const INPUT = resolve(ROOT, 'docs/benchmarks/dynamic-view-latest.json');
const OUTPUT = resolve(ROOT, 'docs/benchmarks/dynamic-view-latest.md');

const result = JSON.parse(readFileSync(INPUT, 'utf8'));

const mark = (pass) => (pass ? '✅' : '❌');
const lines = [];

lines.push('# Dynamic Viewing Benchmark — recorded results');
lines.push('');
lines.push('Generated by `npm run bench`. **Do not edit by hand** — regenerate it.');
lines.push('The machine-readable record is `dynamic-view-latest.json`; this is a rendering of it.');
lines.push('');
lines.push(`- Recorded at: \`${result.recordedAt}\``);
lines.push(`- Browser: \`${result.browser}\``);
lines.push(`- Renderer: \`${result.renderer}\``);
lines.push(`- Soak length: ${result.soakMinutes} minute(s)`);
lines.push('');
lines.push('## Samples');
lines.push('');
lines.push('| Profile | Mode | Source | Visible characters | TTI (ms) | Avg FPS | P5 FPS | Worst FPS | Frames sampled |');
lines.push('|---|---|---|---:|---:|---:|---:|---:|---:|');
for (const sample of result.samples) {
  // ART-173. The label travels with the figure: a row a reader could take as「Mistwood has forty
  // residents」would be worse than the gap the probe closes, and this file is read long after the
  // run that produced it. `-1` TTI means "not measured", not "instant" — the probe is a bare
  // renderer mount with no shell to become interactive.
  const source = sample.loadProbe === true ? '**load probe**' : 'live page';
  const tti = sample.timeToInteractiveMs < 0 ? '—' : sample.timeToInteractiveMs;
  lines.push(
    `| ${sample.profileId} | ${sample.mode} | ${source} | ${sample.characterCount} | ${tti} `
    + `| ${sample.averageFps} | ${sample.p5Fps} | ${sample.worstFps} | ${sample.frameSamples} |`,
  );
}
if (result.samples.some((sample) => sample.loadProbe === true)) {
  lines.push('');
  lines.push(
    '> Rows marked **load probe** are `src/e2e/spriteLoadWorld.ts`: N synthetic animated sprites '
    + 'driving the same renderer, the same sheets and the same motion clock as the live map, with '
    + 'no page shell, no queries and no camera. They measure NFR2-002 AC#4 renderer capacity at '
    + 'the twenty and forty visible characters FR-Q005 asks for. **They are not a claim about how '
    + 'many residents Mistwood has** — it has twelve — and they carry no time-to-interactive, '
    + 'because a bare renderer mount has no shell to become interactive.',
  );
  lines.push('');
}

lines.push('');
lines.push('## Verdicts against NFR2-002');
lines.push('');
lines.push('| Criterion | Profile | Mode | Metric | Value | Threshold | |');
lines.push('|---|---|---|---|---:|---:|:--:|');
for (const verdict of result.verdicts) {
  lines.push(
    `| ${verdict.criterion} | ${verdict.profileId} | ${verdict.mode} | ${verdict.metric} `
    + `| ${verdict.value} | ${verdict.threshold} | ${mark(verdict.pass)} |`,
  );
}
if (result.soak) {
  const { verdict, sampleCount, durationMs } = result.soak;
  // A soak shorter than the criterion measures the slope, and settles nothing. Rendering it as
  // ✅ is what put「AC#7 … ✅」next to a two-minute run in this file for a criterion that names
  // eight hours; the run length is now printed in the same cell as the mark.
  // `=== true`, not `!== false`: a results file recorded before ART-178 has no such field, and an
  // unknown run length must not read as a settled criterion. Missing means unsettled.
  const settles = verdict.settlesCriterion === true;
  const requiredMinutes = Math.round((verdict.requiredDurationMs ?? 8 * 60 * 60 * 1000) / 60_000);
  lines.push(
    `| ${verdict.criterion} | ${result.soak.profileId} | soak (${Math.round(durationMs / 60_000)}m, `
    + `${sampleCount} samples) | ${verdict.metric} | ${verdict.value} | ${verdict.threshold} `
    + `| ${settles ? mark(verdict.pass) : '⚠️'} |`,
  );
  if (!settles) {
    lines.push('');
    lines.push(
      `> **AC#7 is not settled by this run.** The heap slope is ${verdict.value} B/min, within the `
      + `${verdict.threshold} B/min threshold — but the criterion asks for a ${requiredMinutes}-minute `
      + `run and this one lasted ${Math.round(durationMs / 60_000)}. That is evidence the harness can `
      + 'DETECT growth, not evidence that a full-length run is clean. Re-run with '
      + `\`BENCH_SOAK_MINUTES=${requiredMinutes} npm run bench\` to settle it.`,
    );
    lines.push('');
  }
}
lines.push(
  `| AC#5 | desktop-reference | throttled ${result.semanticStability.throttledRate}× | semantic position unchanged `
  + `| ${result.semanticStability.identical} | true | ${mark(result.semanticStability.identical)} |`,
);

lines.push('');
lines.push('## Not measured here, and why');
lines.push('');
lines.push('A gate that silently drops what it cannot measure reports green for a system nobody');
lines.push('measured. These are stated instead.');
lines.push('');
lines.push('| Criterion | Metric | Status | Reason |');
lines.push('|---|---|---|---|');
const gaps = [...result.notMeasured];
// The short soak belongs in this table for the reason the table exists: a criterion the run did
// not settle must be stated, not dropped. It was previously stated nowhere and marked ✅ above.
if (result.soak && result.soak.verdict.settlesCriterion !== true) {
  const { verdict, durationMs } = result.soak;
  gaps.push({
    criterion: verdict.criterion,
    metric: 'soakDurationMs',
    status: 'run_too_short',
    reason:
      `Ran ${Math.round(durationMs / 60_000)} minute(s) of the `
      + `${Math.round((verdict.requiredDurationMs ?? 8 * 60 * 60 * 1000) / 60_000)} the criterion names. The slope `
      + `measured (${verdict.value} B/min) is within threshold, but a short run cannot answer a `
      + 'question about a long one.',
  });
}
for (const gap of gaps) {
  lines.push(`| ${gap.criterion} | \`${gap.metric}\` | \`${gap.status}\` | ${gap.reason} |`);
}
lines.push('');

writeFileSync(OUTPUT, `${lines.join('\n')}\n`, 'utf8');

// A verdict that does not settle its criterion is neither a pass nor a failure of the gate: it
// is not a measurement of that criterion at all, so it is excluded rather than counted either way.
const measured = [
  ...result.verdicts,
  ...(result.soak && result.soak.verdict.settlesCriterion === true ? [result.soak.verdict] : []),
  {
    criterion: 'AC#5',
    metric: 'semanticPositionUnchanged',
    pass: result.semanticStability.identical,
  },
];
const failures = measured.filter((verdict) => !verdict.pass);
console.log(`Wrote ${OUTPUT}`);
console.log(`${measured.length - failures.length}/${measured.length} measured criteria passed.`);
for (const failure of failures) {
  console.error(`FAIL ${failure.criterion} ${failure.metric}: ${failure.value} vs ${failure.threshold}`);
}
process.exit(failures.length === 0 ? 0 : 1);
